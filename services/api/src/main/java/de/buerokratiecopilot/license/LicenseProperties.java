package de.buerokratiecopilot.license;

import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Configuration of the runtime licence check.
 *
 * <p>The values are supplied by the installer through the environment. Nothing here has a
 * production default that would silently turn a licensed installation into an unlicensed one:
 * enforcement is off unless a profile turns it on, and a missing key is a state, not a fallback
 * (see {@link LicenseService}).</p>
 */
@ConfigurationProperties(prefix = "burokratie.license")
public class LicenseProperties {

    /**
     * Whether the runtime licence is enforced at all. The {@code runtime} profile sets it to
     * true; development and tests leave it false so that a checkout without a licence behaves
     * exactly as before.
     */
    private boolean enforced = false;

    /** The compact licence token itself. Takes precedence over {@link #keyFile}. */
    private String key = "";

    /** A file containing the compact licence token, read at startup. */
    private String keyFile = "";

    /**
     * The shared HMAC secret. It is deliberately not a fallback constant: without it the
     * application reports {@code LICENSE_MISSING} instead of accepting an unverifiable key.
     */
    private String secret = "";

    /** File with the installation's instance identifier, generated by the installer. */
    private String instanceIdFile = "/app/data/instance-id";

    /** How long an expired licence remains fully usable as a grace period. */
    private int graceDays = 14;

    /**
     * The cabinet's public licence-status endpoint, e.g.
     * {@code https://agents.firmspace.de/api/license/status}. Empty disables the remote check:
     * the installation then trusts the signature only, exactly as before revocation existed.
     */
    private String checkUrl = "";

    /**
     * Where the last known revocation answer is cached. It is deliberately next to the other
     * installation data so a restart does not forget a revocation while the cabinet is down.
     */
    private String stateFile = "/app/data/license-state.json";

    public boolean isEnforced() {
        return enforced;
    }

    public void setEnforced(boolean enforced) {
        this.enforced = enforced;
    }

    public String getKey() {
        return key;
    }

    public void setKey(String key) {
        this.key = key;
    }

    public String getKeyFile() {
        return keyFile;
    }

    public void setKeyFile(String keyFile) {
        this.keyFile = keyFile;
    }

    public String getSecret() {
        return secret;
    }

    public void setSecret(String secret) {
        this.secret = secret;
    }

    public String getInstanceIdFile() {
        return instanceIdFile;
    }

    public void setInstanceIdFile(String instanceIdFile) {
        this.instanceIdFile = instanceIdFile;
    }

    public int getGraceDays() {
        return graceDays;
    }

    public void setGraceDays(int graceDays) {
        this.graceDays = graceDays;
    }

    public String getCheckUrl() {
        return checkUrl;
    }

    public void setCheckUrl(String checkUrl) {
        this.checkUrl = checkUrl;
    }

    public String getStateFile() {
        return stateFile;
    }

    public void setStateFile(String stateFile) {
        this.stateFile = stateFile;
    }
}
