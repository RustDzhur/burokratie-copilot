-- =====================================================================================
-- V34 - what the platform does with a document once it has understood it
--
-- Until now a document was received, processed and then left lying: nothing connected "this is a
-- Mahnung" to "somebody has to decide something by this date". document_type_scenarios is that
-- connection. One row per document type says which action the document asks for, how urgent it is,
-- which case type it belongs to, what the task is called, which fields carry its dates and what has
-- to be true before the matter counts as finished.
--
-- tenant_id is nullable on purpose, like case_types: the platform ships the global rows, and a
-- tenant may override one for its own type without touching the others.
--
-- The same migration fills two gaps that made the earlier stages produce nothing useful:
--   * 56 of 77 document types had no classification rule, so such a document could never be typed;
--   * 72 of 77 types had no field definition, so nothing was extracted from them.
-- =====================================================================================

CREATE TABLE document_type_scenarios (
    id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id           uuid REFERENCES tenants (id) ON DELETE CASCADE,
    document_type_code  varchar(80) NOT NULL REFERENCES document_types (code) ON DELETE CASCADE,
    action_kind         varchar(20) NOT NULL,
    priority            varchar(15) NOT NULL,
    case_type_code      varchar(80),
    creates_task        boolean NOT NULL DEFAULT true,
    task_title          varchar(200),
    completion_criteria text,
    checklist           text,
    due_field_keys      varchar(300),
    amount_field_keys   varchar(300),
    default_due_days    integer,
    lead_days           integer NOT NULL DEFAULT 2,
    requires_approval   boolean NOT NULL DEFAULT false,
    requires_human_review boolean NOT NULL DEFAULT false,
    legal_deadline      boolean NOT NULL DEFAULT false,
    creates_contract    boolean NOT NULL DEFAULT false,
    follow_up_days      integer,
    follow_up_title     varchar(200),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT document_type_scenarios_action_chk CHECK (action_kind IN
        ('PAY', 'REPLY', 'REVIEW', 'SIGN', 'PROVIDE', 'DECIDE', 'CONTRACT', 'CONFIRM', 'FILE_ONLY')),
    CONSTRAINT document_type_scenarios_priority_chk CHECK (priority IN
        ('CRITICAL', 'HIGH', 'NORMAL', 'LOW', 'INFORMATIONAL')),
    CONSTRAINT document_type_scenarios_task_chk CHECK (NOT creates_task OR task_title IS NOT NULL)
);

CREATE UNIQUE INDEX document_type_scenarios_unique
    ON document_type_scenarios (COALESCE(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid),
                                document_type_code);

ALTER TABLE document_type_scenarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_type_scenarios FORCE ROW LEVEL SECURITY;
CREATE POLICY document_type_scenarios_tenant_isolation ON document_type_scenarios
    USING (tenant_id IS NULL OR tenant_id = current_tenant_id())
    WITH CHECK (tenant_id IS NULL OR tenant_id = current_tenant_id());

-- The task the orchestrator creates for a document must not be created twice when the
-- processing-completed event is delivered twice.
CREATE UNIQUE INDEX tasks_one_per_source_document_idx
    ON tasks (source_document_id)
    WHERE source = 'DOCUMENT' AND source_document_id IS NOT NULL AND parent_task_id IS NULL
      AND deleted_at IS NULL;

