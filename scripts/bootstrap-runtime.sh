#!/usr/bin/env bash
# =============================================================================
#  bootstrap-runtime.sh — first-run provisioning of a Firmspace Robots Runtime
# =============================================================================
#  What it does, in order:
#    1. reads the installation's env file (default infra/runtime.env);
#    2. makes sure the data directory and its instance id exist (the licence is
#       bound to that id);
#    3. starts the Compose stack and waits for /actuator/health/readiness;
#    4. creates tenant + default workspace + owner + the first API token through
#       the application, never through hand-written SQL;
#    5. prints the API URL, tenant/workspace ids, the token ONCE, the licence
#       state and the bridge snippet.
#
#  The token is printed to stdout and written nowhere. Store it in the bridge's
#  secret store; the database keeps only its SHA-256 hash.
#
#  Usage:
#      scripts/bootstrap-runtime.sh
#      scripts/bootstrap-runtime.sh --env-file infra/runtime.env \
#          --tenant "Muster GmbH" --email ops@example.de
#      scripts/bootstrap-runtime.sh --skip-compose          # stack already up
#
#  Exit codes: 0 success, 1 configuration/runtime error, 2 usage error,
#              3 health timeout, 4 bootstrap refused.
# =============================================================================
set -euo pipefail
umask 077

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
PROG="$(basename "$0")"

ENV_FILE="${REPO_ROOT}/infra/runtime.env"
COMPOSE_FILE="${REPO_ROOT}/infra/docker-compose.runtime.yml"
TENANT="${BC_RUNTIME_TENANT:-}"
EMAIL="${BC_RUNTIME_OWNER_EMAIL:-}"
OWNER_NAME="${BC_RUNTIME_OWNER_NAME:-Runtime Owner}"
API_BASE="${BC_API_BASE:-}"
TIMEOUT="${BC_BOOTSTRAP_TIMEOUT:-240}"
SKIP_COMPOSE=0

log()  { printf '%s: %s\n' "$PROG" "$*" >&2; }
warn() { printf '%s: WARNING: %s\n' "$PROG" "$*" >&2; }
die()  { printf '%s: ERROR: %s\n' "$PROG" "$*" >&2; exit 1; }
usage() { sed -n '2,30p' "$0" | sed -n 's/^# \{0,1\}//p'; }

while [ "$#" -gt 0 ]; do
    case "$1" in
        -h|--help)       usage; exit 0 ;;
        --env-file)      [ "$#" -ge 2 ] || die "--env-file needs a value"; ENV_FILE="$2"; shift 2 ;;
        --compose-file)  [ "$#" -ge 2 ] || die "--compose-file needs a value"; COMPOSE_FILE="$2"; shift 2 ;;
        --tenant)        [ "$#" -ge 2 ] || die "--tenant needs a value"; TENANT="$2"; shift 2 ;;
        --email)         [ "$#" -ge 2 ] || die "--email needs a value"; EMAIL="$2"; shift 2 ;;
        --name)          [ "$#" -ge 2 ] || die "--name needs a value"; OWNER_NAME="$2"; shift 2 ;;
        --api-base)      [ "$#" -ge 2 ] || die "--api-base needs a value"; API_BASE="$2"; shift 2 ;;
        --timeout)       [ "$#" -ge 2 ] || die "--timeout needs a value"; TIMEOUT="$2"; shift 2 ;;
        --skip-compose)  SKIP_COMPOSE=1; shift ;;
        *)               printf '%s: unknown option: %s\n' "$PROG" "$1" >&2; usage >&2; exit 2 ;;
    esac
done

[ -r "$ENV_FILE" ] || die "cannot read the env file: ${ENV_FILE} (run scripts/install-runtime.sh first)"
[ -r "$COMPOSE_FILE" ] || die "cannot read the compose file: ${COMPOSE_FILE}"
command -v docker >/dev/null 2>&1 || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "docker compose (v2) is not available"
command -v curl >/dev/null 2>&1 || die "curl is required"

case "$(uname -s)" in
    Darwin) PERMS="$(stat -f '%Lp' "$ENV_FILE" 2>/dev/null || echo unknown)" ;;
    *)      PERMS="$(stat -c '%a' "$ENV_FILE" 2>/dev/null || echo unknown)" ;;
esac
case "$PERMS" in
    600|400) ;;
    *) warn "environment file ${ENV_FILE} has mode ${PERMS}; it contains secrets and should be 600" ;;
esac

# The env file is generated by the installer, is not world-readable and is the
# documented place for these values. Sourcing it keeps one source of truth for
# the compose command and this script.
set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

[ -n "${BC_DB_PASSWORD:-}" ] || die "BC_DB_PASSWORD is empty in ${ENV_FILE}"
[ -n "${BC_ENCRYPTION_KEY:-}" ] || die "BC_ENCRYPTION_KEY is empty in ${ENV_FILE}"
[ -n "${BC_RUNTIME_ADMIN_TOKEN:-}" ] || die "BC_RUNTIME_ADMIN_TOKEN is empty in ${ENV_FILE}"
[ "${#BC_RUNTIME_ADMIN_TOKEN}" -ge 32 ] || die "BC_RUNTIME_ADMIN_TOKEN must be at least 32 characters"
case "$BC_RUNTIME_ADMIN_TOKEN" in
    *[!A-Za-z0-9._~+/=-]*) die "BC_RUNTIME_ADMIN_TOKEN may only contain [A-Za-z0-9._~+/=-]" ;;
esac

DATA_DIR="${BC_DATA_DIR:-${REPO_ROOT}/infra/runtime-data}"
case "$DATA_DIR" in
    /*) ;;
    *) DATA_DIR="${REPO_ROOT}/${DATA_DIR}" ;;
esac
mkdir -p "$DATA_DIR"
chmod 700 "$DATA_DIR" 2>/dev/null || true

INSTANCE_FILE="${DATA_DIR}/instance-id"
if [ ! -s "$INSTANCE_FILE" ]; then
    if command -v uuidgen >/dev/null 2>&1; then
        INSTANCE_ID="$(uuidgen | tr '[:upper:]' '[:lower:]')"
    elif [ -r /proc/sys/kernel/random/uuid ]; then
        INSTANCE_ID="$(tr '[:upper:]' '[:lower:]' < /proc/sys/kernel/random/uuid)"
    else
        INSTANCE_ID="$(openssl rand -hex 16 2>/dev/null || true)"
    fi
    [ -n "$INSTANCE_ID" ] || die "could not generate an instance id (install uuidgen or openssl)"
    printf '%s\n' "$INSTANCE_ID" > "$INSTANCE_FILE"
    log "generated instance id ${INSTANCE_ID} in ${INSTANCE_FILE}"
fi
chmod 600 "$INSTANCE_FILE" 2>/dev/null || true
INSTANCE_ID="$(tr -d '[:space:]' < "$INSTANCE_FILE")"
[ -n "$INSTANCE_ID" ] || die "instance id file ${INSTANCE_FILE} is empty"

PORT="${BC_API_PORT:-8080}"
if [ -z "$API_BASE" ]; then
    # A port published on one specific LAN address is not reachable on
    # 127.0.0.1; follow the bind address instead of assuming loopback.
    case "${BC_BIND_ADDRESS:-127.0.0.1}" in
        0.0.0.0|::|127.0.0.1|localhost) HOST="${BC_BOOTSTRAP_HEALTH_HOST:-127.0.0.1}" ;;
        *) HOST="${BC_BOOTSTRAP_HEALTH_HOST:-${BC_BIND_ADDRESS}}" ;;
    esac
    API_BASE="http://${HOST}:${PORT}"
fi
API_BASE="${API_BASE%/}"

if [ "$SKIP_COMPOSE" -eq 0 ]; then
    log "starting the runtime stack (${COMPOSE_FILE})"
    docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" up -d
fi

log "waiting for ${API_BASE}/actuator/health/readiness (up to ${TIMEOUT}s)"
DEADLINE=$((SECONDS + TIMEOUT))
HEALTHY=0
while [ "$SECONDS" -lt "$DEADLINE" ]; do
    if curl -fsS --max-time 3 "${API_BASE}/actuator/health/readiness" 2>/dev/null \
            | grep -q '"status"[[:space:]]*:[[:space:]]*"UP"'; then
        HEALTHY=1
        break
    fi
    sleep 3
done
if [ "$HEALTHY" -ne 1 ]; then
    warn "the API did not become healthy in ${TIMEOUT}s; last log lines:"
    docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" logs --tail=60 api >&2 || true
    exit 3
fi
log "API is healthy"

json_string() {
    # json_string '<json>' '<key>' — first string value for a key (flat payloads only).
    printf '%s' "$1" | sed -n 's/.*"'"$2"'"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1
}
json_bool() {
    printf '%s' "$1" | grep -Eq '"'"$2"'"[[:space:]]*:[[:space:]]*true'
}
http_post() {
    # http_post <path> <body> <output-file>; prints the HTTP status.
    local path="$1" body="$2" out="$3"
    curl -sS -o "$out" -w '%{http_code}' --max-time 30 \
        -H "Content-Type: application/json" \
        -H "X-Runtime-Admin-Token: ${BC_RUNTIME_ADMIN_TOKEN}" \
        -X POST "${API_BASE}${path}" --data-binary "$body" || true
}

STATUS_BODY="$(mktemp "${TMPDIR:-/tmp}/bc-runtime-status.XXXXXX")"
RESPONSE_FILE=""
cleanup() { rm -f "${STATUS_BODY:-}" "${RESPONSE_FILE:-}"; }
trap cleanup EXIT
STATUS_CODE="$(curl -sS -o "$STATUS_BODY" -w '%{http_code}' --max-time 20 \
    -H "X-Runtime-Admin-Token: ${BC_RUNTIME_ADMIN_TOKEN}" \
    "${API_BASE}/api/v1/runtime/status" || true)"

BOOTSTRAPPED=0
TENANT_ID=""
WORKSPACE_ID=""
if [ "$STATUS_CODE" = "200" ] && json_bool "$(cat "$STATUS_BODY")" bootstrapped; then
    BOOTSTRAPPED=1
    TENANT_ID="$(json_string "$(cat "$STATUS_BODY")" tenantId)"
    WORKSPACE_ID="$(json_string "$(cat "$STATUS_BODY")" workspaceId)"
elif [ "$STATUS_CODE" = "401" ] || [ "$STATUS_CODE" = "404" ]; then
    cat "$STATUS_BODY" >&2 || true
    die "the runtime admin token was refused (HTTP ${STATUS_CODE}); check BC_RUNTIME_ADMIN_TOKEN in ${ENV_FILE}"
elif [ "$STATUS_CODE" != "200" ]; then
    cat "$STATUS_BODY" >&2 || true
    die "could not read /api/v1/runtime/status (HTTP ${STATUS_CODE})"
fi

RESPONSE_FILE="$(mktemp "${TMPDIR:-/tmp}/bc-runtime-bootstrap.XXXXXX")"

if [ "$BOOTSTRAPPED" -eq 0 ]; then
    [ -n "$TENANT" ] || die "no tenant name; pass --tenant (or set BC_RUNTIME_TENANT)"
    [ -n "$EMAIL" ] || die "no owner e-mail; pass --email (or set BC_RUNTIME_OWNER_EMAIL)"
    log "creating tenant, workspace and owner"
    BODY="$(printf '{"tenantName":"%s","ownerEmail":"%s","ownerName":"%s"}' \
        "$(printf '%s' "$TENANT" | sed 's/\\/\\\\/g; s/"/\\"/g')" \
        "$(printf '%s' "$EMAIL" | sed 's/\\/\\\\/g; s/"/\\"/g')" \
        "$(printf '%s' "$OWNER_NAME" | sed 's/\\/\\\\/g; s/"/\\"/g')")"
    CODE="$(http_post /api/v1/runtime/bootstrap "$BODY" "$RESPONSE_FILE")"
    case "$CODE" in
        201) ;;
        409)
            cat "$RESPONSE_FILE" >&2 || true
            printf '%s: ERROR: the installation was bootstrapped by another process; re-run this script to issue a token.\n' "$PROG" >&2
            exit 4 ;;
        *)
            cat "$RESPONSE_FILE" >&2 || true
            die "bootstrap failed (HTTP ${CODE})" ;;
    esac
else
    log "installation is already bootstrapped; issuing a new bridge token"
    BODY='{"name":"runtime-bridge","scopes":["agents.view","agents.run","documents:write"]}'
    CODE="$(http_post /api/v1/runtime/tokens "$BODY" "$RESPONSE_FILE")"
    if [ "$CODE" != "201" ]; then
        cat "$RESPONSE_FILE" >&2 || true
        die "token issuance failed (HTTP ${CODE}); no new credential was created"
    fi
fi

RESPONSE="$(cat "$RESPONSE_FILE")"
TOKEN="$(json_string "$RESPONSE" token)"
TOKEN_ID="$(json_string "$RESPONSE" id)"
if [ -z "$TOKEN_ID" ]; then
    TOKEN_ID="$(json_string "$RESPONSE" tokenId)"
fi
PREFIX="$(json_string "$RESPONSE" prefix)"
TENANT_ID="$(json_string "$RESPONSE" tenantId)"
WORKSPACE_ID="$(json_string "$RESPONSE" workspaceId)"
if [ -z "$TENANT_ID" ]; then
    TENANT_ID="$(json_string "$(cat "$STATUS_BODY")" tenantId)"
fi
if [ -z "$WORKSPACE_ID" ]; then
    WORKSPACE_ID="$(json_string "$(cat "$STATUS_BODY")" workspaceId)"
fi
[ -n "$TOKEN" ] || die "the server did not return a token"

LICENSE_JSON="$(curl -fsS --max-time 10 "${API_BASE}/api/v1/license" || true)"
LICENSE_STATE="$(json_string "$LICENSE_JSON" state)"
LICENSE_PLAN="$(json_string "$LICENSE_JSON" plan)"
LICENSE_CUSTOMER="$(json_string "$LICENSE_JSON" customer)"
LICENSE_EXPIRES="$(json_string "$LICENSE_JSON" expiresAt)"
# A perpetual licence has no expiresAt; saying "n/a" would read like "unknown".
LICENSE_ENDS="${LICENSE_EXPIRES:-perpetual (no expiry)}"
EXTERNAL_URL="${BC_PUBLIC_BASE_URL:-$API_BASE}"
EXTERNAL_URL="${EXTERNAL_URL%/}"

cat <<EOF

Firmspace Robots Runtime — installation ready
=============================================

API URL:       ${EXTERNAL_URL}
Local health:  ${API_BASE}/actuator/health/readiness
Tenant:        ${TENANT_ID}
Workspace:     ${WORKSPACE_ID}
Instance id:   ${INSTANCE_ID}
Licence:       ${LICENSE_STATE:-unknown}${LICENSE_PLAN:+ (plan ${LICENSE_PLAN})}${LICENSE_CUSTOMER:+, ${LICENSE_CUSTOMER}}
Licence ends:  ${LICENSE_ENDS}
Token id:      ${TOKEN_ID} (prefix ${PREFIX})
Token:         ${TOKEN}

This token is shown ONCE. The server stores only its SHA-256 hash.
Store it in the bridge's secret store and do not paste it into a ticket.

Bridge / agent client:
  export BC_API_URL="${EXTERNAL_URL}"
  export BC_API_TOKEN="${TOKEN}"
  curl -fsS "\$BC_API_URL/api/v1/agents" -H "Authorization: Bearer \$BC_API_TOKEN"

Run an agent:
  curl -fsS -X POST "\$BC_API_URL/api/v1/agents/doc-detect/run" \\
    -H "Authorization: Bearer \$BC_API_TOKEN" -H "Content-Type: application/json" \\
    -d '{"trigger":"manual","inputs":{"fileName":"rechnung-0411.pdf"}}'

Token administration (same admin secret as the installer):
  curl -fsS "\$BC_API_URL/api/v1/runtime/tokens" \\
    -H "X-Runtime-Admin-Token: <BC_RUNTIME_ADMIN_TOKEN>"
  curl -fsS -X POST "\$BC_API_URL/api/v1/runtime/tokens/<token-id>/revoke" \\
    -H "X-Runtime-Admin-Token: <BC_RUNTIME_ADMIN_TOKEN>"

Next:
  * install a licence key if the state is LICENSE_MISSING and restart the api:
      LICENSE_KEY=... in ${ENV_FILE}; docker compose --env-file ${ENV_FILE} \\
        -f ${COMPOSE_FILE} up -d api
  * the runtime has no web UI; all management is this API (see docs/deployment/RUNTIME.md).
EOF

if [ "${LICENSE_STATE:-}" = "LICENSE_MISSING" ]; then
    warn "no valid licence is installed: agent endpoints answer 402 until LICENSE_KEY is set"
elif [ "${LICENSE_STATE:-}" = "LICENSE_GRACE" ]; then
    warn "the licence has expired and the installation is in its grace period"
fi
